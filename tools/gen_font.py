#!/usr/bin/env python3
"""Generate a compact 1-bit CJK/ASCII bitmap font for the SSD1306 UI.

Rasterises a fixed character set from a macOS system CJK font at 12 px and
emits src/font_cn.h: a sorted glyph table plus one bitmap blob.

    /Users/hanson0901/.dsh/dsh-runtimes/dsh-primary-runtime/dependencies/python/bin/python3 \
        tools/gen_font.py

The firmware does binary search by Unicode code point, so the table must stay
sorted; the generator guarantees that.
"""

from __future__ import annotations

import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "font_cn.h")
PREVIEW = os.path.join(ROOT, "build", "font_preview.png")

FONT_CANDIDATES = [
    "/System/Library/Fonts/STHeiti Medium.ttc",
    "/System/Library/Fonts/STHeiti Light.ttc",
    "/System/Library/Fonts/Hiragino Sans GB.ttc",
]
SIZE = 12
THRESHOLD = 96

# Static UI vocabulary + the characters that show up in short DSH messages.
CHARS = (
    "待命中思考回覆執行工具需要授權錯誤連線未已裝置模型推理程度秒前分鐘清除訊息"
    "網路設定伺服器無法連接逾時失敗重試等待正在準備完成狀態工作讀取寫入待機休眠"
    "喚醒系統斷線上下沒有問題請稍候好的是不在到你我們這那個了嗎呢啊喔恩嗯會能以"
    "超過顯示範圍目前時間日期星期一二三四五六日年月總計數量觸發更新同步暫停恢復"
    "啟動關閉開啟測試確認取消選擇輸入輸出檔案圖片語音視訊記憶容量已用剩餘百分比"
    "電量訊號強度線路徑埠位址金鑰權限申請允許拒絕核准要求回應處理排程佇列任務步"
    "驟階段回合對話內容摘要全文版本韌體設備節點感測溫度濕度亮度距離動作異常警告"
    "嚴重輕微原因說明詳細資訊紀錄日誌事件歷史最近最後第一第二第三左邊右邊中間底"
    "部上方下方前後左右大小長短高低快慢新舊冷熱開關機重啟燒錄晶片位元組"
    "就緒指令看面板序"
    "，。、：；！？（）「」…·—／＋－＝％　"
)

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))


def pick_font() -> ImageFont.FreeTypeFont:
    for path in FONT_CANDIDATES:
        if os.path.exists(path):
            try:
                return ImageFont.truetype(path, SIZE, index=0)
            except OSError:
                continue
    sys.exit("no usable CJK font found")


def main() -> None:
    font = pick_font()
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent

    chars = sorted({ord(c) for c in ASCII + CHARS})
    glyphs = []
    blob = bytearray()
    preview = Image.new("L", (360, cell_h * 3), 0)
    pdraw = ImageDraw.Draw(preview)
    ptext = "待命中 思考中 需要授權 錯誤 deepseek-flash"

    for cp in chars:
        ch = chr(cp)
        advance = max(1, int(round(font.getlength(ch))))
        img = Image.new("L", (advance, cell_h), 0)
        draw = ImageDraw.Draw(img)
        draw.text((0, ascent), ch, font=font, fill=255, anchor="ls")
        img = img.point(lambda p: 255 if p > THRESHOLD else 0)
        pixels = img.load()

        stride = (advance + 7) // 8
        offset = len(blob)
        for y in range(cell_h):
            for bx in range(stride):
                byte = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < advance and pixels[x, y]:
                        byte |= 1 << (7 - bit)
                blob.append(byte)
        glyphs.append((cp, advance, cell_h, advance, offset))

    pdraw.text((4, ascent), ptext, font=font, fill=255)
    pdraw.text((4, ascent + cell_h + 2), "連線未已逾時清除", font=font, fill=160)
    os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
    preview.resize((preview.width * 2, preview.height * 2), Image.NEAREST).save(PREVIEW)

    lines = [
        "// Generated by tools/gen_font.py -- do not edit by hand.",
        "// Font: %s %dpx (ascent %d, descent %d)" % (font.getname()[0], SIZE, ascent, descent),
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#define CN_FONT_ASCENT %d" % ascent,
        "#define CN_FONT_DESCENT %d" % descent,
        "#define CN_FONT_CELL_H %d" % cell_h,
        "",
        "struct CnGlyph { uint16_t cp; uint8_t w; uint8_t h; uint8_t adv; uint16_t off; };",
        "",
        "static const uint8_t CN_FONT_BITS[] = {",
    ]
    for i in range(0, len(blob), 16):
        lines.append("  " + ",".join(str(b) for b in blob[i : i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("static const CnGlyph CN_FONT_GLYPHS[] = {")
    for cp, w, h, adv, off in glyphs:
        lines.append("  {%d,%d,%d,%d,%d}," % (cp, w, h, adv, off))
    lines.append("};")
    lines.append("")
    lines.append("#define CN_FONT_COUNT %d" % len(glyphs))

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print("font:", font.getname(), "cell", cell_h, "glyphs", len(glyphs), "bytes", len(blob))
    print("header:", OUT, os.path.getsize(OUT), "bytes")
    print("preview:", PREVIEW)


if __name__ == "__main__":
    main()
